# -*- coding: utf-8 -*-
"""Weather add-on: emits wxmood_tbl.h, each species' weather affinity from its type.

0 none, 1 water, 2 fire, 3 grass, 4 ice, 5 electric, 6 rock/ground.
Run: python3 tools/gen_wxmood.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from dex_data import DEX

AFF = {'agua': 1, 'fuego': 2, 'planta': 3, 'hielo': 4, 'electrico': 5, 'roca': 6, 'tierra': 6}
tbl = [0] * 152
for num, _slug, _disp, tipo, _evo, _lvl in DEX:
    tbl[num] = AFF.get(tipo, 0)
out = os.path.join(os.path.dirname(__file__), '..', 'wxmood_tbl.h')
with open(out, 'w') as f:
    f.write('// GENERATED by tools/gen_wxmood.py from tools/dex_data.py - do not edit\n#pragma once\n#include <stdint.h>\n')
    f.write('// weather affinity by dex number: 0 none 1 water 2 fire 3 grass 4 ice 5 electric 6 rock/ground\n')
    f.write('static const uint8_t WX_AFFINITY[152] = {\n')
    for i in range(0, 152, 19):
        f.write('  ' + ', '.join(str(v) for v in tbl[i:i + 19]) + ',\n')
    f.write('};\n')
print('wrote', out, 'counts:', {k: tbl.count(v) for k, v in AFF.items()})
